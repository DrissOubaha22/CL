"""What the model is allowed to return (spec §4.2).

The shape mirrors the specification's example exactly.  It is a *strict*
schema: the model cannot add fields, and every material claim must carry the
source that backs it.  Anything that does not fit is a rejected extraction,
not a repaired one.

Two rules are structural rather than checked later:

* ``cve_id`` is not in this schema at all.  Spec §4.2: "CVE IDs are never
  generated by the model."  The pipeline knows which CVE it fetched a page
  for and supplies it; the model is never asked.
* Every claim field is optional.  A model that cannot find a fact returns
  nothing for it, which is the honest answer, rather than guessing to fill
  a required field.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field, field_validator

from aegis.core.enums import Confidence, ExploitStatus

__all__ = ["AdvisoryExtraction", "ExtractedSource"]


class ExtractedSource(BaseModel):
    """A citation the model must supply for each material claim."""

    model_config = ConfigDict(extra="forbid")

    url: str = Field(min_length=1, max_length=2048)
    #: The sentence in the page that supports the claim.  Lets a reviewer
    #: check the extraction without re-reading the whole advisory, and makes
    #: a fabricated claim obvious.
    quote: str = Field(min_length=1, max_length=1000)
    #: Which field this citation backs, when the model can say.
    field: str | None = Field(default=None, max_length=64)

    @field_validator("quote")
    @classmethod
    def _collapse_whitespace(cls, value: str) -> str:
        return " ".join(value.split())


class AdvisoryExtraction(BaseModel):
    """Structured fields extracted from one vendor advisory page."""

    model_config = ConfigDict(extra="forbid")

    #: none | poc | active, per spec §4.2's example.
    exploit_status: ExploitStatus | None = None
    #: The vendor states the vulnerability is being exploited.  Spec §7.2
    #: treats this as KEV-equivalent, so it is the highest-stakes field here.
    vendor_confirmed: bool | None = None
    patch_available: bool | None = None
    #: The advisory conditions exploitability on a feature or setting
    #: (spec §5.3).
    config_dependent: bool | None = None
    #: Free-text version statements as the vendor wrote them, e.g.
    #: "FortiMail < 7.6.3".  Parsing them into CPE ranges is a separate,
    #: deterministic step; the model is not asked to invent CPE strings.
    affected_versions: list[str] = Field(default_factory=list, max_length=50)

    sources: list[ExtractedSource] = Field(default_factory=list, max_length=20)
    confidence: Confidence = Confidence.LOW
    #: The model's own note on anything ambiguous, shown to a reviewer.
    reviewer_note: str | None = Field(default=None, max_length=1000)

    @field_validator("affected_versions")
    @classmethod
    def _clean_versions(cls, value: list[str]) -> list[str]:
        cleaned: list[str] = []
        for item in value:
            text = " ".join(str(item).split())
            if text and text not in cleaned:
                cleaned.append(text[:200])
        return cleaned

    @property
    def asserts_anything(self) -> bool:
        """Did the model find any material claim at all?"""
        return any(
            (
                self.exploit_status is not None,
                self.vendor_confirmed is not None,
                self.patch_available is not None,
                self.config_dependent is not None,
                bool(self.affected_versions),
            )
        )
