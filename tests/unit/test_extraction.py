"""LLM advisory extraction and its validation - spec §4.2."""

from __future__ import annotations

import httpx
import pytest
import respx
from pydantic import ValidationError

from aegis.config import Settings
from aegis.core.enums import Confidence, ExploitStatus
from aegis.intel.extraction.fetch import (
    AdvisoryFetchError,
    fetch_advisory_text,
    html_to_text,
)
from aegis.intel.extraction.schemas import AdvisoryExtraction, ExtractedSource
from aegis.intel.extraction.validation import (
    independent_publishers,
    registrable_domain,
    validate_extraction,
)

CVE = "CVE-2026-104286"


def source(url: str, field: str | None = "exploit_status", quote: str = "exploited in the wild"):
    return ExtractedSource(url=url, quote=quote, field=field)


def extraction(**overrides: object) -> AdvisoryExtraction:
    fields: dict[str, object] = {
        "exploit_status": ExploitStatus.ACTIVE,
        "vendor_confirmed": True,
        "confidence": Confidence.HIGH,
    }
    fields.update(overrides)
    return AdvisoryExtraction(**fields)  # type: ignore[arg-type]


class TestSchema:
    def test_the_model_cannot_supply_a_cve_id(self) -> None:
        """Spec §4.2: CVE IDs are never generated by the model."""
        assert "cve_id" not in AdvisoryExtraction.model_fields
        with pytest.raises(ValidationError):
            AdvisoryExtraction(cve_id="CVE-2026-1")  # type: ignore[call-arg]

    def test_unknown_fields_are_rejected(self) -> None:
        with pytest.raises(ValidationError):
            AdvisoryExtraction(severity="critical")  # type: ignore[call-arg]

    def test_every_claim_field_is_optional(self) -> None:
        """An unset field is the honest answer when the page says nothing."""
        empty = AdvisoryExtraction()
        assert empty.exploit_status is None
        assert empty.patch_available is None
        assert not empty.asserts_anything

    def test_version_statements_are_kept_as_written(self) -> None:
        """The model is told not to convert them; this keeps them intact."""
        parsed = AdvisoryExtraction(
            affected_versions=["FortiMail  <  7.6.3", "7.4.x < 7.4.8", "FortiMail  <  7.6.3"]
        )
        assert parsed.affected_versions == ["FortiMail < 7.6.3", "7.4.x < 7.4.8"]

    def test_a_citation_needs_a_quote(self) -> None:
        with pytest.raises(ValidationError):
            ExtractedSource(url="https://psirt.test/a", quote="")


class TestRegistrableDomain:
    @pytest.mark.parametrize(
        ("url", "expected"),
        [
            ("https://psirt.fortinet.com/advisory", "fortinet.com"),
            ("https://www.fortinet.com/a/b", "fortinet.com"),
            ("http://cisa.gov/alert", "cisa.gov"),
            ("https://news.example.co.uk/x", "example.co.uk"),
            ("not-a-url", None),
            ("ftp://files.example.com/a", None),
            ("", None),
        ],
    )
    def test_publisher_extraction(self, url: str, expected: str | None) -> None:
        assert registrable_domain(url) == expected


class TestIndependence:
    def test_two_urls_on_one_site_are_one_publisher(self) -> None:
        publishers = independent_publishers(
            [
                source("https://fortinet.com/psirt/1"),
                source("https://psirt.fortinet.com/2"),
            ]
        )
        assert publishers == {"fortinet.com"}

    def test_different_sites_are_independent(self) -> None:
        publishers = independent_publishers(
            [source("https://fortinet.com/psirt/1"), source("https://cisa.gov/a")]
        )
        assert publishers == {"fortinet.com", "cisa.gov"}

    def test_a_citation_without_a_quote_does_not_count(self) -> None:
        """Spec §4.2 requires a supporting quote; a bare URL asserts nothing."""
        assert independent_publishers([source("https://fortinet.com/a", quote=" ")]) == set()


class TestValidation:
    def test_unsourced_claims_are_discarded(self) -> None:
        """Spec §4.2: discarded, not downgraded."""
        result = validate_extraction(extraction(sources=[]), expected_cve_id=CVE)

        assert result.discarded == ["exploit_status", "vendor_confirmed"]
        assert result.extraction.exploit_status is None
        assert result.extraction.vendor_confirmed is None
        assert result.needs_review

    def test_two_independent_sources_clear_the_bar(self) -> None:
        result = validate_extraction(
            extraction(
                sources=[
                    source("https://fortinet.com/psirt/1", "exploit_status"),
                    source("https://cisa.gov/alert", "exploit_status"),
                    source("https://fortinet.com/psirt/1", "vendor_confirmed"),
                    source("https://cisa.gov/alert", "vendor_confirmed"),
                ]
            ),
            expected_cve_id=CVE,
        )

        assert result.accepted["exploit_status"] == 2
        assert not result.needs_review
        assert result.confidence is Confidence.HIGH

    def test_a_single_high_stakes_source_forces_review(self) -> None:
        """vendor_confirmed causes out-of-hours escalation under §7.2."""
        result = validate_extraction(
            extraction(sources=[source("https://fortinet.com/psirt/1", "vendor_confirmed")]),
            expected_cve_id=CVE,
        )

        assert result.single_sourced
        assert result.confidence is Confidence.LOW
        assert result.needs_review

    def test_a_single_low_stakes_source_only_caps_confidence(self) -> None:
        result = validate_extraction(
            AdvisoryExtraction(
                patch_available=True,
                confidence=Confidence.HIGH,
                sources=[source("https://fortinet.com/psirt/1", "patch_available")],
            ),
            expected_cve_id=CVE,
        )

        assert result.accepted == {"patch_available": 1}
        assert result.confidence is Confidence.MEDIUM

    def test_claims_fall_back_to_the_pages_own_publishers(self) -> None:
        """A citation without a field still backs what the page asserts."""
        result = validate_extraction(
            extraction(
                sources=[
                    source("https://fortinet.com/psirt/1", field=None),
                    source("https://cisa.gov/alert", field=None),
                ]
            ),
            expected_cve_id=CVE,
        )
        assert result.accepted["exploit_status"] == 2

    def test_a_model_flagged_ambiguity_forces_review(self) -> None:
        result = validate_extraction(
            extraction(
                sources=[
                    source("https://fortinet.com/a", "exploit_status"),
                    source("https://cisa.gov/b", "exploit_status"),
                    source("https://fortinet.com/a", "vendor_confirmed"),
                    source("https://cisa.gov/b", "vendor_confirmed"),
                ],
                reviewer_note="The page describes a related CVE in the same paragraph.",
            ),
            expected_cve_id=CVE,
        )
        assert result.needs_review

    def test_an_empty_extraction_needs_review(self) -> None:
        result = validate_extraction(AdvisoryExtraction(), expected_cve_id=CVE)
        assert not result.has_claims
        assert result.needs_review


class TestHtmlToText:
    def test_scripts_and_styles_are_dropped(self) -> None:
        text = html_to_text(
            "<html><style>a{color:red}</style><body><p>Exploited in the wild.</p>"
            "<script>fetch('/x')</script></body></html>"
        )
        assert "Exploited in the wild." in text
        assert "color:red" not in text
        assert "fetch" not in text

    def test_entities_are_decoded(self) -> None:
        assert "FortiMail < 7.6.3" in html_to_text("<p>FortiMail &lt; 7.6.3</p>")

    def test_block_ends_become_line_breaks(self) -> None:
        assert html_to_text("<p>one</p><p>two</p>").splitlines() == ["one", "two"]


class TestFetch:
    @respx.mock
    def test_fetches_and_reduces_a_page(self) -> None:
        respx.get("https://psirt.test/FG-IR-26-001").mock(
            return_value=httpx.Response(
                200,
                headers={"content-type": "text/html"},
                text="<html><body><p>Exploited in the wild.</p></body></html>",
            )
        )
        payload = fetch_advisory_text("https://psirt.test/FG-IR-26-001", settings=Settings())
        assert payload.kind == "advisory_page"
        assert "Exploited in the wild." in payload.text
        assert payload.source_url == "https://psirt.test/FG-IR-26-001"

    @respx.mock
    def test_an_error_status_is_reported(self) -> None:
        respx.get("https://psirt.test/missing").mock(return_value=httpx.Response(404))
        with pytest.raises(AdvisoryFetchError, match="404"):
            fetch_advisory_text("https://psirt.test/missing", settings=Settings())

    @respx.mock
    def test_an_empty_page_is_refused(self) -> None:
        respx.get("https://psirt.test/blank").mock(
            return_value=httpx.Response(
                200,
                headers={"content-type": "text/html"},
                text="<html><body></body></html>",
            )
        )
        with pytest.raises(AdvisoryFetchError, match="no readable text"):
            fetch_advisory_text("https://psirt.test/blank", settings=Settings())

    @respx.mock
    def test_a_plain_text_advisory_is_taken_as_written(self) -> None:
        """Some PSIRTs publish .txt advisories; do not strip them as markup."""
        respx.get("https://psirt.test/plain.txt").mock(
            return_value=httpx.Response(
                200,
                headers={"content-type": "text/plain; charset=utf-8"},
                text="FG-IR-26-001\nFortiMail < 7.6.3 is exploited in the wild.",
            )
        )
        payload = fetch_advisory_text("https://psirt.test/plain.txt", settings=Settings())
        assert "FortiMail < 7.6.3" in payload.text

    @respx.mock
    def test_a_page_with_no_content_type_is_treated_as_markup(self) -> None:
        """The safer default: strip tags rather than hand markup to a model."""
        respx.get("https://psirt.test/untyped").mock(
            # `content=` rather than `text=`: httpx adds a text/plain header
            # for the latter, which is not what a bare response looks like.
            return_value=httpx.Response(200, content=b"<p>Exploited in the wild.</p>")
        )
        payload = fetch_advisory_text("https://psirt.test/untyped", settings=Settings())
        assert payload.text == "Exploited in the wild."

    @respx.mock
    def test_a_transport_failure_is_reported(self) -> None:
        respx.get("https://psirt.test/down").mock(side_effect=httpx.ConnectError("refused"))
        with pytest.raises(AdvisoryFetchError, match="cannot fetch"):
            fetch_advisory_text("https://psirt.test/down", settings=Settings())
